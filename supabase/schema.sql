-- STEP 8: Supabase table matching the app's request records.
-- Columns match the API contract in README.md:
-- id, created_at, requester_name, location, description, priority, status

create table public.requests (
  -- Auto-numbered id (the seed import supplies ids 1-22 so they match the app).
  id             bigint generated by default as identity primary key,
  -- Timestamp with time zone; seed values are UTC ("...Z").
  created_at     timestamptz not null default now(),
  requester_name text not null check (char_length(btrim(requester_name)) > 0),
  location       text not null
                 check (location in ('Minneapolis', 'Chicago', 'Denver', 'Austin')),
  description    text not null
                 check (char_length(btrim(description)) between 1 and 500),
  priority       text not null
                 check (priority in ('Low', 'Medium', 'High', 'Urgent')),
  status         text not null default 'New'
                 check (status in ('New', 'In Progress', 'Complete'))
);

-- The list endpoint and export sort newest first.
create index requests_created_at_idx on public.requests (created_at desc);

-- Row Level Security: Supabase blocks all access through its API until
-- policies allow it. The app uses the public (anon) key, so allow exactly
-- what the app does — read, add, and change status — and nothing else
-- (no deletes). The CHECK constraints above still apply to every write.
alter table public.requests enable row level security;

create policy "Anyone can read requests"
  on public.requests for select
  to anon
  using (true);

create policy "Anyone can add requests"
  on public.requests for insert
  to anon
  with check (true);

create policy "Anyone can update requests"
  on public.requests for update
  to anon
  using (true)
  with check (true);

-- Column-level limits for the public key:
-- new rows may only supply the four form fields (the database sets id,
-- created_at and status = 'New'), and updates may only change status.
revoke insert, update, delete, truncate on public.requests from anon;
-- This project does not grant table access to anon by default, so the
-- read policy above only works with an explicit SELECT grant.
grant select on public.requests to anon;
grant insert (requester_name, location, description, priority)
  on public.requests to anon;
grant update (status) on public.requests to anon;
